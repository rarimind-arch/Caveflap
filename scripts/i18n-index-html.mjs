// One-time script: adds data-i18n(-placeholder/-aria-label) attributes to the
// static markup in index.html and writes matching keys into src/i18n/en.json.
// Each replacement is an exact, unique string match (like the Edit tool), so
// a mismatch fails loudly instead of silently corrupting the file.
import fs from 'node:fs';

const path = 'index.html';
let html = fs.readFileSync(path, 'utf8');
const en = {};

function rep(from, to, key, value) {
  const count = html.split(from).length - 1;
  if (count !== 1) throw new Error(`expected exactly 1 occurrence of ${JSON.stringify(from)}, found ${count}`);
  html = html.replace(from, to);
  if (key) en[key] = value;
}

